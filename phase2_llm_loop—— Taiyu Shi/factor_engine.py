"""A small, restricted expression language for LLM-proposed factors.

Expressions are parsed with ``ast.parse(mode="eval")`` and interpreted node by
node. Only allowlisted inputs, operators and functions are accepted, so nothing
generated by the LLM is ever executed as Python code: no attribute access,
indexing, imports, keyword arguments, lambdas or comprehensions can be
expressed. Every time-series function is trailing-window only and its history
requirement is added to a running lookback total, which must stay within
``config.MAX_LOOKBACK`` trading days. Negative lags or windows are rejected, so
future values cannot be referenced.
"""

import ast
from dataclasses import dataclass

import numpy as np
import pandas as pd

import config


class FactorExpressionError(ValueError):
    """Raised when an expression is not allowed or cannot be computed."""

    def __init__(self, code, message):
        super().__init__(message)
        self.code = code


# input name -> history (in trading days) needed beyond the current row
INPUT_LOOKBACK = {}
for _ticker in config.TICKERS:
    _p = _ticker.lower()
    for _field in config.PRICE_FIELDS:
        INPUT_LOOKBACK[f"{_p}_{_field}"] = 0
    INPUT_LOOKBACK[f"{_p}_ret1"] = 1
    INPUT_LOOKBACK[f"{_p}_logvol"] = 0
ALLOWED_INPUTS = tuple(INPUT_LOOKBACK)

ELEMENTWISE_UNARY = {"log": np.log, "abs": np.abs, "sign": np.sign, "sqrt": np.sqrt, "tanh": np.tanh}
ELEMENTWISE_BINARY = {"maximum": np.maximum, "minimum": np.minimum}
# name -> (number of series arguments, minimum integer, maximum integer)
WINDOW_FUNCTIONS = {
    "lag": (1, 1, config.MAX_LOOKBACK),
    "diff": (1, 1, config.MAX_LOOKBACK),
    "pct_change": (1, 1, config.MAX_LOOKBACK),
    "rolling_mean": (1, 2, config.MAX_LOOKBACK),
    "rolling_std": (1, 2, config.MAX_LOOKBACK),
    "rolling_min": (1, 2, config.MAX_LOOKBACK),
    "rolling_max": (1, 2, config.MAX_LOOKBACK),
    "rolling_sum": (1, 2, config.MAX_LOOKBACK),
    "zscore": (1, 2, config.MAX_LOOKBACK),
    "rolling_corr": (2, 3, config.MAX_LOOKBACK),
}
ALLOWED_FUNCTIONS = tuple(ELEMENTWISE_UNARY) + tuple(ELEMENTWISE_BINARY) + ("clip",) + tuple(WINDOW_FUNCTIONS)

LANGUAGE_REFERENCE = f"""\
Inputs (date-aligned daily series): {{asset}}_{{field}} with asset in aapl, msft, nvda, qqq and
field in open, high, low, close, volume, ret1, logvol. ret1 = 1-day log return of close,
logvol = ln(volume). Example names: aapl_close, qqq_ret1, nvda_logvol.
Operators: + - * / and parentheses; unary minus. Numeric constants with |c| <= {config.MAX_ABS_CONSTANT:g}.
Elementwise functions: log(x), abs(x), sign(x), sqrt(x), tanh(x), maximum(x, y), minimum(x, y),
clip(x, lo, hi) with numeric lo/hi.
Trailing time-series functions (k, w must be integer literals):
  lag(x, k)            value k days ago,             1 <= k <= {config.MAX_LOOKBACK}
  diff(x, k)           x_t - x_(t-k),                1 <= k <= {config.MAX_LOOKBACK}
  pct_change(x, k)     x_t / x_(t-k) - 1,            1 <= k <= {config.MAX_LOOKBACK}
  rolling_mean|rolling_std|rolling_min|rolling_max|rolling_sum(x, w)   2 <= w <= {config.MAX_LOOKBACK}
  zscore(x, w)         (x - rolling_mean) / rolling_std,             2 <= w <= {config.MAX_LOOKBACK}
  rolling_corr(x, y, w) trailing correlation,                         3 <= w <= {config.MAX_LOOKBACK}
Lookback rule: nested history adds up (input lookback + k for lag/diff/pct_change, + w-1 for rolling
functions). The total must be <= {config.MAX_LOOKBACK} trading days. Example: rolling_mean(aapl_ret1, 20)
needs 1 + 19 = 20 days (allowed); zscore(diff(aapl_close, 5), 20) needs 5 + 19 = 24 (rejected).
Not allowed: powers, comparisons, conditionals, attributes, indexing, keyword arguments, strings,
negative lags, the target, and anything referring to future data. Division by values near zero
yields missing values.
"""


@dataclass
class ComputedFactor:
    values: pd.Series
    lookback: int
    inputs_used: tuple
    canonical: str


def parse_expression(expression):
    if not isinstance(expression, str) or not expression.strip():
        raise FactorExpressionError("EMPTY_EXPRESSION", "Expression must be a non-empty string")
    if len(expression) > config.MAX_EXPRESSION_CHARS:
        raise FactorExpressionError("EXPRESSION_TOO_LONG",
                                    f"Expression exceeds {config.MAX_EXPRESSION_CHARS} characters")
    try:
        tree = ast.parse(expression.strip(), mode="eval")
    except SyntaxError as exc:
        raise FactorExpressionError("SYNTAX_ERROR", f"Invalid expression syntax: {exc.msg}") from exc
    if sum(1 for _ in ast.walk(tree)) > config.MAX_EXPRESSION_NODES:
        raise FactorExpressionError("EXPRESSION_TOO_LARGE",
                                    f"Expression exceeds {config.MAX_EXPRESSION_NODES} syntax nodes")
    return tree.body


def canonical_form(expression):
    """Whitespace-insensitive representation used to detect duplicate expressions."""
    return ast.dump(parse_expression(expression), annotate_fields=False)


def _integer(node, lower, upper, op):
    value = None
    if isinstance(node, ast.Constant) and type(node.value) is int:
        value = node.value
    elif (isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub)
          and isinstance(node.operand, ast.Constant) and type(node.operand.value) is int):
        value = -node.operand.value
    if value is None:
        raise FactorExpressionError("BAD_ARGUMENT", f"{op}: window/lag must be an integer literal")
    if value < 0:
        raise FactorExpressionError("FUTURE_REFERENCE",
                                    f"{op}: negative argument {value} would reference future data")
    if not lower <= value <= upper:
        raise FactorExpressionError("BAD_ARGUMENT", f"{op}: integer argument {value} outside [{lower}, {upper}]")
    return value


def _number(node, op):
    sign = 1.0
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        sign, node = -1.0, node.operand
    if not isinstance(node, ast.Constant) or type(node.value) not in (int, float):
        raise FactorExpressionError("BAD_ARGUMENT", f"{op}: bounds must be numeric constants")
    return sign * float(node.value)


def compute_expression(wide, expression):
    """Evaluate ``expression`` on ``wide`` and return a ComputedFactor."""
    tree = parse_expression(expression)
    used = set()

    def check_lookback(lookback):
        if lookback > config.MAX_LOOKBACK:
            raise FactorExpressionError("LOOKBACK_EXCEEDED",
                                        f"Expression needs {lookback} days of history "
                                        f"(limit {config.MAX_LOOKBACK})")
        return lookback

    def visit(node, depth):
        if depth > config.MAX_EXPRESSION_DEPTH:
            raise FactorExpressionError("EXPRESSION_TOO_DEEP", "Expression is nested too deeply")
        if isinstance(node, ast.Name):
            if "target" in node.id.lower() or "future" in node.id.lower() or "next" in node.id.lower():
                raise FactorExpressionError("FUTURE_REFERENCE", f"Input refers to the target or future data: {node.id}")
            if node.id not in INPUT_LOOKBACK:
                raise FactorExpressionError("UNKNOWN_INPUT", f"Unknown input column: {node.id}")
            if node.id not in wide.columns:
                raise FactorExpressionError("UNKNOWN_INPUT", f"Input column missing from data: {node.id}")
            used.add(node.id)
            return wide[node.id].astype(float), INPUT_LOOKBACK[node.id]
        if isinstance(node, ast.Constant):
            if type(node.value) not in (int, float) or not np.isfinite(node.value) \
                    or abs(node.value) > config.MAX_ABS_CONSTANT:
                raise FactorExpressionError("BAD_CONSTANT",
                                            f"Only finite numeric constants with |c| <= "
                                            f"{config.MAX_ABS_CONSTANT:g} are allowed")
            return float(node.value), 0
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.USub, ast.UAdd)):
            value, lookback = visit(node.operand, depth + 1)
            return (-value if isinstance(node.op, ast.USub) else value), lookback
        if isinstance(node, ast.BinOp):
            left, left_lb = visit(node.left, depth + 1)
            right, right_lb = visit(node.right, depth + 1)
            if isinstance(node.op, ast.Add):
                result = left + right
            elif isinstance(node.op, ast.Sub):
                result = left - right
            elif isinstance(node.op, ast.Mult):
                result = left * right
            elif isinstance(node.op, ast.Div):
                if isinstance(right, pd.Series):
                    right = right.where(right.abs() > 1e-12)
                elif abs(right) <= 1e-12:
                    raise FactorExpressionError("DIVISION_BY_ZERO", "Division by a zero constant")
                result = left / right
            else:
                raise FactorExpressionError("DISALLOWED_SYNTAX", "Only +, -, * and / operators are allowed")
            return result, max(left_lb, right_lb)
        if isinstance(node, ast.Call):
            if not isinstance(node.func, ast.Name) or node.func.id not in ALLOWED_FUNCTIONS:
                name = getattr(node.func, "id", type(node.func).__name__)
                raise FactorExpressionError("DISALLOWED_FUNCTION", f"Function not allowed: {name}")
            if node.keywords:
                raise FactorExpressionError("DISALLOWED_SYNTAX", "Keyword arguments are not allowed")
            return call(node.func.id, node.args, depth)
        raise FactorExpressionError("DISALLOWED_SYNTAX", f"Unsupported syntax: {type(node).__name__}")

    def series_arg(node, depth, op):
        value, lookback = visit(node, depth + 1)
        if not isinstance(value, pd.Series):
            raise FactorExpressionError("BAD_ARGUMENT", f"{op} requires a time series argument")
        return value, lookback

    def call(op, args, depth):
        if op in ELEMENTWISE_UNARY:
            if len(args) != 1:
                raise FactorExpressionError("BAD_ARGUMENT", f"{op} expects 1 argument")
            value, lookback = visit(args[0], depth + 1)
            return ELEMENTWISE_UNARY[op](value), lookback
        if op in ELEMENTWISE_BINARY:
            if len(args) != 2:
                raise FactorExpressionError("BAD_ARGUMENT", f"{op} expects 2 arguments")
            (a, a_lb), (b, b_lb) = visit(args[0], depth + 1), visit(args[1], depth + 1)
            return ELEMENTWISE_BINARY[op](a, b), max(a_lb, b_lb)
        if op == "clip":
            if len(args) != 3:
                raise FactorExpressionError("BAD_ARGUMENT", "clip expects 3 arguments")
            value, lookback = series_arg(args[0], depth, op)
            lower, upper = _number(args[1], op), _number(args[2], op)
            if lower >= upper:
                raise FactorExpressionError("BAD_ARGUMENT", "clip: lower bound must be below upper bound")
            return value.clip(lower, upper), lookback
        n_series, lower, upper = WINDOW_FUNCTIONS[op]
        if len(args) != n_series + 1:
            raise FactorExpressionError("BAD_ARGUMENT", f"{op} expects {n_series + 1} arguments")
        value, lookback = series_arg(args[0], depth, op)
        k = _integer(args[-1], lower, upper, op)
        if op == "lag":
            return value.shift(k), check_lookback(lookback + k)
        if op == "diff":
            return value.diff(k), check_lookback(lookback + k)
        if op == "pct_change":
            previous = value.shift(k)
            return value / previous.where(previous.abs() > 1e-12) - 1, check_lookback(lookback + k)
        if op == "rolling_corr":
            other, other_lb = series_arg(args[1], depth, op)
            return value.rolling(k).corr(other), check_lookback(max(lookback, other_lb) + k - 1)
        if op == "zscore":
            std = value.rolling(k).std()
            result = (value - value.rolling(k).mean()) / std.where(std > 1e-12)
            return result, check_lookback(lookback + k - 1)
        method = op.removeprefix("rolling_")
        return getattr(value.rolling(k), method)(), check_lookback(lookback + k - 1)

    with np.errstate(divide="ignore", invalid="ignore", over="ignore"):
        result, lookback = visit(tree, 0)
    if not isinstance(result, pd.Series):
        raise FactorExpressionError("NOT_A_SERIES", "Expression must produce a time series, not a constant")
    result = pd.to_numeric(result, errors="coerce").astype(float).replace([np.inf, -np.inf], np.nan)
    return ComputedFactor(values=result, lookback=check_lookback(lookback),
                          inputs_used=tuple(sorted(used)), canonical=ast.dump(tree, annotate_fields=False))
